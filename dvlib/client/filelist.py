"""dvlib.f generation: simulator-agnostic filelist in topological compile order.

Deepest dependency first, alphabetical tie-break for determinism. Emits
+incdir+, +define+NAME=VALUE, and ordered source files with paths relative
to the project root. Works for VCS/Xcelium/Questa-style filelists.
"""

from __future__ import annotations

import heapq
from dataclasses import dataclass
from pathlib import Path

from ..common.manifest import Manifest, load_manifest

__all__ = ["FilelistError", "generate_filelist", "topo_order", "PACKAGES_DIR", "FILELIST_NAME"]

PACKAGES_DIR = "dvlib_packages"
FILELIST_NAME = "dvlib.f"


class FilelistError(Exception):
    pass


@dataclass
class InstalledPackage:
    name: str
    manifest: Manifest
    path: Path  # absolute path to dvlib_packages/<name>


def load_installed(project_root: Path | str) -> dict[str, InstalledPackage]:
    """Read manifests of everything under dvlib_packages/."""
    root = Path(project_root) / PACKAGES_DIR
    out: dict[str, InstalledPackage] = {}
    if not root.is_dir():
        return out
    for child in sorted(root.iterdir()):
        if not child.is_dir():
            continue
        manifest = load_manifest(child)
        out[manifest.name] = InstalledPackage(manifest.name, manifest, child)
    return out


def topo_order(packages: dict[str, InstalledPackage]) -> list[str]:
    """Deepest dependency first; alphabetical tie-break. Dependencies on
    packages that are not installed (e.g. tool-provided UVM) are ignored."""
    deps: dict[str, set[str]] = {
        name: {d for d in pkg.manifest.dependencies if d in packages}
        for name, pkg in packages.items()
    }
    dependents: dict[str, set[str]] = {name: set() for name in packages}
    for name, ds in deps.items():
        for d in ds:
            dependents[d].add(name)
    ready = [n for n, ds in deps.items() if not ds]
    heapq.heapify(ready)
    order: list[str] = []
    while ready:
        name = heapq.heappop(ready)
        order.append(name)
        for dependent in dependents[name]:
            deps[dependent].discard(name)
            if not deps[dependent]:
                heapq.heappush(ready, dependent)
    if len(order) != len(packages):
        cycle = ", ".join(sorted(set(packages) - set(order)))
        raise FilelistError(f"dependency cycle detected among: {cycle}")
    return order


def _package_lines(pkg: InstalledPackage, project_root: Path) -> list[str]:
    rel_root = pkg.path.relative_to(project_root).as_posix()
    lines: list[str] = []
    for inc in pkg.manifest.include_dirs:
        lines.append(f"+incdir+{rel_root}/{inc}")
    for define in pkg.manifest.defines:
        lines.append(f"+define+{define}")
    for f in pkg.manifest.files:
        lines.append(f"{rel_root}/{f}")
    return lines


def generate_filelist(project_root: Path | str) -> Path:
    """Generate dvlib.f at the project root plus per-package .f fragments."""
    project_root = Path(project_root)
    packages = load_installed(project_root)
    order = topo_order(packages)

    # Per-package fragments.
    for name in order:
        pkg = packages[name]
        fragment = pkg.path / f"{name}.f"
        fragment.write_text("\n".join(_package_lines(pkg, project_root)) + "\n", encoding="utf-8")

    lines: list[str] = ["// Generated by dvlib. Do not edit by hand."]
    for name in order:
        lines.append(f"// --- {name} ---")
        lines.extend(_package_lines(packages[name], project_root))
    out = project_root / FILELIST_NAME
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out

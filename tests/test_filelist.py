import pytest

from dvlib.client.filelist import FilelistError, generate_filelist, load_installed, topo_order


def install_pkg(root, name, deps=None, files=None):
    d = root / "dvlib_packages" / name
    (d / "src").mkdir(parents=True)
    files = files or [f"src/{name}_pkg.sv"]
    dep_toml = ""
    if deps:
        dep_toml = "[dependencies]\n" + "".join(f'{k} = "{v}"\n' for k, v in deps.items())
    (d / "dvlib.toml").write_text(
        f'[package]\nname="{name}"\nversion="1.0.0"\n'
        f'[compile]\nfiles={files!r}\ninclude_dirs=["src"]\ndefines=["{name.upper()}"]\n'
        f"{dep_toml}".replace("'", '"')
    )
    for f in files:
        p = d / f
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(f"// {name}\n")
    return d


class TestTopoOrder:
    def test_deepest_first_alphabetical_tiebreak(self, tmp_path):
        install_pkg(tmp_path, "top", deps={"a": "^1", "b": "^1"})
        install_pkg(tmp_path, "a", deps={"base": "^1"})
        install_pkg(tmp_path, "b", deps={"base": "^1"})
        install_pkg(tmp_path, "base")
        order = topo_order(load_installed(tmp_path))
        assert order[0] == "base"
        assert order[1:3] == ["a", "b"]  # alphabetical tie-break
        assert order[3] == "top"

    def test_unknown_dep_ignored(self, tmp_path):
        install_pkg(tmp_path, "vip", deps={"uvm": "^1"})  # tool-provided UVM
        assert topo_order(load_installed(tmp_path)) == ["vip"]

    def test_cycle_detected(self, tmp_path):
        install_pkg(tmp_path, "a", deps={"b": "^1"})
        install_pkg(tmp_path, "b", deps={"a": "^1"})
        with pytest.raises(FilelistError, match="cycle"):
            topo_order(load_installed(tmp_path))


class TestGenerateFilelist:
    def test_content_and_fragments(self, tmp_path):
        install_pkg(tmp_path, "top", deps={"base": "^1"})
        install_pkg(tmp_path, "base")
        out = generate_filelist(tmp_path)
        content = out.read_text()
        lines = [ln for ln in content.splitlines() if ln.endswith(".sv")]
        assert lines[0].startswith("dvlib_packages/base/")
        assert lines[1].startswith("dvlib_packages/top/")
        assert "+incdir+dvlib_packages/base/src" in content
        assert "+define+BASE" in content
        assert (tmp_path / "dvlib_packages" / "base" / "base.f").is_file()
        assert (tmp_path / "dvlib_packages" / "top" / "top.f").is_file()

    def test_no_packages_writes_empty_generated_filelist(self, tmp_path):
        out = generate_filelist(tmp_path)
        assert out.read_text() == "// Generated by dvlib. Do not edit by hand.\n"
